#!/usr/bin/env python3
"""Generate common/unicode_tables.h: code-point ranges for \\p{L} and \\p{N}.

The Hugging Face byte-level pre-tokenizer uses the GPT-2 regex
    's|'t|'re|'ve|'m|'ll|'d| ?\\p{L}+| ?\\p{N}+| ?[^\\s\\p{L}\\p{N}]+|\\s+(?!\\S)|\\s+
and the Digits pre-tokenizer splits on \\p{N}. To match it exactly in C++ without
ICU we embed the category ranges, generated from Python's unicodedata.

Usage: python3 tools/gen_unicode_tables.py > common/unicode_tables.h
"""
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(cp)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, rs):
    lines = [f"static const uint32_t {name}[][2] = {{"]
    row = []
    for a, b in rs:
        row.append(f"{{0x{a:X},0x{b:X}}}")
        if len(row) == 6:
            lines.append("  " + ",".join(row) + ",")
            row = []
    if row:
        lines.append("  " + ",".join(row) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    letter = ranges(lambda cp: unicodedata.category(chr(cp)).startswith("L"))
    number = ranges(lambda cp: unicodedata.category(chr(cp)).startswith("N"))
    print("// Generated by tools/gen_unicode_tables.py -- do not edit.")
    print(f"// Unicode {unicodedata.unidata_version}: general categories L* and N*.")
    print("#pragma once")
    print("#include <cstdint>")
    print("namespace tf {")
    print(emit("kLetterRanges", letter))
    print(emit("kNumberRanges", number))
    print(f"static const int kNumLetterRanges = {len(letter)};")
    print(f"static const int kNumNumberRanges = {len(number)};")
    print("}  // namespace tf")


if __name__ == "__main__":
    sys.exit(main())
