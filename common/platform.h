// OS-specific bits, kept out of the rest of the code so everything else can assume UTF-8.
#pragma once
#include <string>
#include <vector>

namespace tf {

// Command-line arguments as UTF-8. On Windows, argv is split from the command line after it has been
// converted to the ANSI code page, which turns anything outside that code page (Hindi, CJK, emoji, ...)
// into '?' or a "best-fit" look-alike. Some look-alikes are delimiters (U+3000 IDEOGRAPHIC SPACE becomes
// a space), so even the number of arguments can be wrong. So on Windows the UTF-16 command line is
// split again with split_command_line().
std::vector<std::string> utf8_args(int argc, char** argv);

// Splits a command line into arguments the way the Microsoft C runtime builds argv (the rules in
// "Parsing C command-line arguments" on Microsoft Learn). Works on UTF-8, which gives the same result as
// splitting the UTF-16 line: the rules only look at space, tab, '"' and '\', and those bytes never occur
// inside a multi-byte UTF-8 character. Plain C++, so it is tested on every OS.
std::vector<std::string> split_command_line(const std::string& line);

// Lets the Windows console show and accept UTF-8, and puts stdout in binary mode so "\n" isn't
// turned into "\r\n" (generated bytes are then identical on every OS). Does nothing elsewhere.
void setup_console();

}  // namespace tf
